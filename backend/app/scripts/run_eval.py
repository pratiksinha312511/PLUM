"""Run all 12 cases and emit a markdown eval report."""
from __future__ import annotations

import asyncio
import json
from pathlib import Path

from app.models.schemas import ClaimSubmission
from app.pipeline import run_pipeline


CASES_FILE = Path(__file__).resolve().parents[3] / "test_cases.json"
OUT_FILE = Path(__file__).resolve().parents[3] / "docs" / "EVAL_REPORT.md"


def _expected_summary(case: dict) -> str:
    e = case.get("expected", {})
    parts = []
    if e.get("decision") is not None:
        parts.append(f"decision={e['decision']}")
    if "approved_amount" in e:
        parts.append(f"approved=₹{e['approved_amount']}")
    if e.get("rejection_reasons"):
        parts.append("reasons=" + ",".join(e["rejection_reasons"]))
    return " · ".join(parts) or "user action / behaviour"


async def main() -> None:
    cases = json.loads(CASES_FILE.read_text(encoding="utf-8"))["test_cases"]
    lines = ["# Eval Report — 12 Official Test Cases", "", f"_Generated by `app.scripts.run_eval`_", ""]

    pass_count = 0
    for case in cases:
        sub = ClaimSubmission.model_validate(case["input"])
        dec = await run_pipeline(sub)

        actual_decision = dec.decision.value if dec.decision else "NONE"
        expected_decision = case["expected"].get("decision")
        match = "✅"
        if expected_decision and expected_decision != actual_decision:
            match = "❌"
        elif expected_decision is None and dec.decision and dec.decision.value not in ("NEEDS_USER_ACTION",):
            match = "❌"

        if match == "✅":
            pass_count += 1

        lines.append(f"## {case['case_id']} — {case['case_name']} {match}")
        lines.append("")
        lines.append(f"**Expected:** {_expected_summary(case)}")
        lines.append("")
        lines.append(
            f"**Actual:** decision=`{actual_decision}` · approved=₹{dec.approved_amount:.0f} · "
            f"confidence={dec.confidence_score}"
        )
        lines.append("")
        if dec.user_action:
            lines.append(f"**User-facing message:** _{dec.user_action.message}_")
            lines.append("")
        if dec.notes:
            lines.append(f"**Notes:** {dec.notes}")
            lines.append("")
        lines.append("**Trace:**")
        lines.append("")
        lines.append("| # | Agent | Status | Summary |")
        lines.append("|---|-------|--------|---------|")
        for i, step in enumerate(dec.trace, 1):
            summary = step.summary.replace("|", "\\|")
            lines.append(f"| {i} | {step.agent} | {step.status} | {summary} |")
        lines.append("")
        if dec.calculation:
            lines.append("<details><summary>Financial breakdown</summary>")
            lines.append("")
            lines.append("```json")
            lines.append(json.dumps(dec.calculation.model_dump(), indent=2))
            lines.append("```")
            lines.append("")
            lines.append("</details>")
            lines.append("")
        lines.append("---\n")

    lines.insert(2, f"**Result: {pass_count}/{len(cases)} passed.**")
    lines.insert(3, "")

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_FILE}")
    print(f"Result: {pass_count}/{len(cases)} passed.")


if __name__ == "__main__":
    asyncio.run(main())
